<div class="wp-block-group is-style-faq"><!-- wp:details {"showContent":true} -->
<details class="wp-block-details" open><summary>What are the membership levels in the SleepTech Network?</summary><!-- wp:paragraph -->
<p>There are three membership levels in the SleepTech Network. Basic ($5,000/year) is the entry point for Network access for start-ups and smaller companies. Standard ($12,500/year) includes upgraded visibility in NSF’s booth at CES. Premium ($25,000/year) includes campaign participation and visibility featuring leadership in sleep health.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What are the benefits of joining the SleepTech Network?</summary><!-- wp:paragraph -->
<p>By joining the network, companies receive evidence-based and consensus-driven recommendations, standards, and content from NSF that can help today’s technology designers, developers, and manufacturers who are working to help improve people’s sleep. Learn more in the <a href="https://www.thensf.org/wp-content/uploads/2025/03/SleepTech_Network_2025_Prospectus.pdf">SleepTech® Network Prospectus</a>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What companies can become a member of the NSF SleepTech Network?</summary><!-- wp:paragraph -->
<p>Any company that designs, develops, manufactures, distributes, or conducts research on sleep health technology solutions can be considered for membership.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>What is the membership year?</summary><!-- wp:paragraph -->
<p>Membership is on a rolling basis. Membership includes 12 months from when the company joins.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Can I use the National Sleep Foundation logo?</summary><!-- wp:paragraph -->
<p>SleepTech Network members are only allowed to use the NSF SleepTech Network logo. Use of the NSF enterprise name and mark is prohibited unless there is a separate licensing agreement in place.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Does my company need to be a member of the SleepTech Network to apply for the SleepTech<sup>®</sup> Award?</summary><!-- wp:paragraph -->
<p>No, membership in the SleepTech Network is not a prerequisite for submitting an application for the <a href="https://www.thensf.org/sleeptech-award/">SleepTech Award</a>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Is my company eligible for membership after being selected as a SleepTech Award winner or finalist?</summary><!-- wp:paragraph -->
<p>Yes. Your company is eligible for SleepTech Network membership regardless of your SleepTech Award status.</p>
